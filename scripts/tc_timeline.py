"""Step 3: emit typed timeline / chapter / sfx / sprite-size modules."""
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BASE = r"D:/下载/跳槽马AI视频-20261110T134214Z-1-001/跳槽马AI视频/02-音频与时刻表"
TT = json.load(open(os.path.join(BASE, "音频时刻表.json"), encoding="utf-8"))
DATA = os.path.join(ROOT, "src", "videos", "Tiaocaoma", "data")
PUBLIC = os.path.join(ROOT, "public", "tiaocaoma")
os.makedirs(DATA, exist_ok=True)

SPEAKER = {
    "旁白": None,
    "店小二": "waiter",
    "店小二·内心OS": "waiter",
    "刀疤脸": "scar",
    "赵大人": "zhao",
    "一品大员": "firstlord",
}
CHAPTER_NAMES = [
    ("壹 · 西馆新规", "看官下菜，马槽也论品级"),
    ("贰 · 瘸马东槽", "刀疤脸与赛赤兔登场"),
    ("叁 · 再犯官府", "解绳扣，冲撞一品大员"),
    ("肆 · 交涉碰壁", "人在马在，赛赤兔之名"),
    ("伍 · 百马畏威", "死扣锁马，众马不敢张嘴"),
    ("陆 · 马王悲歌", "断臂真相，人不如马"),
]

tracks = TT["tracks"]
acts = []
for t in tracks:
    if not acts or acts[-1][0] != t["act"]:
        acts.append([t["act"], []])
    acts[-1][1].append(t)

chapters = []
for i, (act, group) in enumerate(acts):
    label, sub = CHAPTER_NAMES[i] if i < len(CHAPTER_NAMES) else (f"第{i+1}幕", act)
    chapters.append({
        "id": i + 1,
        "label": label,
        "sub": sub,
        "fromFrame": group[0]["startFrame"],
        "toFrame": group[-1]["endFrame"],
    })

out_tracks = []
for t in tracks:
    cid = next(c["id"] for c in chapters if t["startFrame"] >= c["fromFrame"] and t["endFrame"] <= c["toFrame"])
    out_tracks.append({
        "id": t["id"],
        "file": f"{t['id']:02d}.mp3",
        "role": t["role"],
        "speaker": SPEAKER.get(t["role"]),
        "inner": "内心OS" in t["role"],
        "act": t["act"],
        "chapter": cid,
        "emotion": t["emotion"],
        "text": t["text"],
        "startFrame": t["startFrame"],
        "endFrame": t["endFrame"],
        "durationFrames": t["endFrame"] - t["startFrame"],
        "sfx": t["sfx"],
    })

SFX = [
    (94.08, "knock.wav", "木棍笃笃敲槽"),
    (151.98, "hoof_bell.wav", "瘸马铜铃"),
    (363.04, "knee.wav", "双膝砸地"),
    (520.33, "knock_fast.wav", "急促敲槽"),
    (616.04, "sword.wav", "拔剑·喀嚓·木臂落地"),
]


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


with open(os.path.join(DATA, "timeline.ts"), "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by scripts/tc_timeline.py — do not hand-edit.\n")
    f.write("// Source: 音频时刻表.json (54 clips, 0.3s inter-clip silence, 60fps).\n")
    f.write("export const FPS = 60;\n")
    f.write(f"export const TOTAL_SECONDS = {TT['meta']['totalSeconds']};\n")
    f.write(f"export const DURATION_FRAMES = {TT['meta']['totalFrames']};\n\n")
    f.write("export type Speaker = 'scar' | 'waiter' | 'zhao' | 'firstlord' | null;\n\n")
    f.write("export interface Track {\n")
    for field, typ in [("id", "number"), ("file", "string"), ("role", "string"),
                       ("speaker", "Speaker"), ("inner", "boolean"), ("act", "string"),
                       ("chapter", "number"), ("emotion", "string"), ("text", "string"),
                       ("startFrame", "number"), ("endFrame", "number"),
                       ("durationFrames", "number"), ("sfx", "string | null")]:
        f.write(f"  {field}: {typ};\n")
    f.write("}\n\n")
    f.write("export interface Chapter { id: number; label: string; sub: string; fromFrame: number; toFrame: number; }\n\n")
    f.write("export const CHAPTERS: Chapter[] = " + ts(chapters) + ";\n\n")
    f.write("export const TRACKS: Track[] = " + ts(out_tracks) + ";\n\n")
    f.write("export interface SfxEvent { frame: number; file: string; label: string; }\n")
    f.write("export const SFX_EVENTS: SfxEvent[] = " + ts(
        [{"frame": round(s * 60), "file": name, "label": label} for s, name, label in SFX]) + ";\n")

manifest = json.load(open(os.path.join(PUBLIC, "parts", "manifest.json"), encoding="utf-8"))
with open(os.path.join(DATA, "parts.ts"), "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by scripts/tc_timeline.py. Tight bbox of every cut-out part.\n")
    f.write("export interface PartInfo { x: number; y: number; w: number; h: number; cx: number; cy: number; }\n\n")
    f.write("export const PARTS: Record<string, PartInfo> = " + ts(manifest) + ";\n")

print("timeline.ts:", len(out_tracks), "tracks,", len(chapters), "chapters")
print("parts.ts:", len(manifest), "sprites")
